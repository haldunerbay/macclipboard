import AppKit
import ClipCore

/// Polls the general pasteboard (macOS has no change notification) and records every new copy.
@MainActor
final class PasteboardWatcher {
    var isPaused = false

    private let store: HistoryStore
    private let pasteboard = NSPasteboard.general
    /// -1 records what is on the clipboard at launch, so the current item is on top.
    private var lastChangeCount = -1
    private var timer: Timer?

    /// Markers that password managers and similar apps put on content that must not be kept
    /// (nspasteboard.org conventions).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let screenCaptureBundleIDs: Set<String> = ["com.apple.screencaptureui", "com.apple.screenshot.launcher"]
    private static let maxImageBytes = 40 * 1024 * 1024

    init(store: HistoryStore) {
        self.store = store
    }

    func start() {
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    /// Call after writing to the pasteboard ourselves, so that write is not recorded again.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !isPaused else { return }
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredTypes) else { return }
        capture()
    }

    private func capture() {
        let source = NSWorkspace.shared.frontmostApplication
        let sourceApp = source?.bundleIdentifier == Bundle.main.bundleIdentifier ? nil : source?.localizedName

        let fileURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if !fileURLs.isEmpty {
            let paths = fileURLs.map(\.path)
            let isScreenshot = paths.count == 1 && ScreenshotFile.isScreenshot(atPath: paths[0])
            store.add(ClipItem(
                category: isScreenshot ? .screenshot : .file,
                filePaths: paths,
                sourceApp: sourceApp,
                contentHash: ClipClassifier.contentHash(filePaths: paths)
            ))
            return
        }

        let string = pasteboard.string(forType: .string).flatMap { ClipClassifier.hasVisibleText($0) ? $0 : nil }
        let link = string.flatMap(ClipClassifier.link(in:))
        // An image wins over text only when the text is nothing more than its address
        // ("Copy Image" in a browser); a table copied from Numbers stays text.
        if string == nil || link != nil, let image = readImage() {
            let isScreenshot = NSWorkspace.shared.runningApplications.contains {
                Self.screenCaptureBundleIDs.contains($0.bundleIdentifier ?? "")
            }
            store.add(
                ClipItem(
                    category: isScreenshot ? .screenshot : .image,
                    pixelWidth: image.width,
                    pixelHeight: image.height,
                    sourceApp: isScreenshot ? "Screenshot" : sourceApp,
                    contentHash: ClipClassifier.contentHash(imageData: image.png)
                ),
                imageData: image.png
            )
            return
        }

        if let string {
            store.add(ClipItem(
                category: link == nil ? .text : .link,
                text: link == nil ? string : string.trimmingCharacters(in: .whitespacesAndNewlines),
                sourceApp: sourceApp,
                contentHash: ClipClassifier.contentHash(text: string.trimmingCharacters(in: .whitespacesAndNewlines))
            ))
            return
        }

        if let url = (pasteboard.readObjects(forClasses: [NSURL.self]) as? [URL])?.first {
            store.add(ClipItem(
                category: .link,
                text: url.absoluteString,
                sourceApp: sourceApp,
                contentHash: ClipClassifier.contentHash(text: url.absoluteString)
            ))
        }
    }

    /// The copied image as PNG. PNG data is kept as it is, so pasting an item from the history
    /// and reading it back gives the same content hash.
    private func readImage() -> (png: Data, width: Int, height: Int)? {
        if let png = pasteboard.data(forType: .png), png.count <= Self.maxImageBytes, let rep = NSBitmapImageRep(data: png) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        guard let tiff = pasteboard.data(forType: .tiff), tiff.count <= Self.maxImageBytes * 4,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:])
        else { return nil }
        return (png, rep.pixelsWide, rep.pixelsHigh)
    }
}
